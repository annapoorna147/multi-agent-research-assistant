
from typing import Literal

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

app = FastAPI(
    title="Multi-Agent Research Assistant",
    description="Research assistant API",
    version="2.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5173",
        "http://127.0.0.1:5173",
    ],
    allow_credentials=False,
    allow_methods=["*"],
    allow_headers=["*"],
)


class ResearchRequest(BaseModel):
    question: str = Field(min_length=3, max_length=2000)
    mode: Literal["Quick", "Standard", "Deep"] = "Standard"


@app.get("/")
def root():
    return {
        "name": "Multi-Agent Research Assistant",
        "status": "online",
    }


@app.get("/health")
def health():
    return {"status": "healthy"}


@app.get("/api/health")
def api_health():
    return {
        "status": "healthy",
        "service": "research-api",
    }


@app.post("/api/research/")
def prepare_research(request: ResearchRequest):
    question = request.question.strip()

    if len(question) < 3:
        from fastapi import HTTPException

        raise HTTPException(
            status_code=422,
            detail="Please enter a research question with at least 3 characters.",
        )

    if request.mode == "Quick":
        key_questions = [
            "What are the main concepts and definitions?",
            "What are the most important findings or applications?",
            "What limitations or unanswered questions remain?",
        ]
    elif request.mode == "Deep":
        key_questions = [
            "What is the background and theoretical foundation?",
            "What does the strongest available evidence show?",
            "Which sources and methods support the main claims?",
            "What competing explanations or contradictory findings exist?",
            "What limitations, assumptions, and research gaps remain?",
            "What conclusions are justified by the evidence?",
        ]
    else:
        key_questions = [
            "What are the key concepts and background?",
            "What evidence supports the main claims?",
            "What are the main applications, limitations, and trade-offs?",
            "What reliable sources are needed to verify the findings?",
        ]

    return {
        "title": "Research plan",
        "question": question,
        "mode": request.mode,
        "summary": (
            "A research plan has been prepared for your topic. "
            "The questions below organize the investigation; "
            "they are not research findings."
        ),
        "key_questions": key_questions,
        "next_steps": [
            "Find credible sources relevant to the question.",
            "Record each source and the evidence it provides.",
            "Compare claims across sources and check for contradictions.",
            "Write conclusions only after evaluating the evidence.",
        ],
        "notice": (
            "This is a preliminary research plan generated by the API. "
            "It does not perform web searches, call an AI model, "
            "or verify factual claims yet."
        ),
    }
